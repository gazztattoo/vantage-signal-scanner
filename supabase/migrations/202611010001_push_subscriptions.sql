-- Global Signal Scanner: suscripciones Web Push por dispositivo.
-- Ejecutar en Supabase PRODUCCIÓN durante la activación aprobada.
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique,
  subscription jsonb not null,
  created_at timestamptz not null default now()
);
alter table public.push_subscriptions enable row level security;
-- Sin políticas públicas: el backend accede con SUPABASE_SECRET_KEY solo en servidor.
