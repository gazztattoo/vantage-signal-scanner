-- Cola persistente de Web Push, con seguimiento individual por dispositivo.
-- Añadir únicamente durante la activación aprobada de producción.
create table if not exists public.push_delivery_outbox (
  id bigint generated by default as identity primary key,
  event_fingerprint text not null,
  endpoint text not null,
  subscription jsonb not null,
  payload jsonb not null,
  status text not null default 'pending'
    check (status in ('pending','sent','dead')),
  attempts integer not null default 0 check (attempts >= 0),
  next_attempt_at timestamptz not null default now(),
  last_error text,
  created_at timestamptz not null default now(),
  delivered_at timestamptz,
  unique (event_fingerprint, endpoint)
);

create index if not exists push_delivery_outbox_due_idx
  on public.push_delivery_outbox (next_attempt_at, created_at)
  where status = 'pending';

create index if not exists push_delivery_outbox_event_idx
  on public.push_delivery_outbox (event_fingerprint);

alter table public.push_delivery_outbox enable row level security;
-- Sin políticas públicas: acceso exclusivo desde el backend con la clave de servidor.
