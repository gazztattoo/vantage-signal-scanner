-- Global Signal Scanner: persistencia de señales y estado de alertas.
-- Aplicar únicamente en Supabase PRODUCCIÓN después de revisar y aprobar el despliegue.

create table if not exists public.signal_history (
  id bigint generated by default as identity primary key,
  signal_key text not null unique,
  symbol text not null,
  timeframe text not null,
  direction text not null check (direction in ('COMPRA','VENTA')),
  entry_price numeric not null,
  stop_loss numeric not null,
  take_profit numeric not null,
  signal_at timestamptz not null default now(),
  candle_time timestamptz,
  status text not null default 'PENDIENTE'
    check (status in ('PENDIENTE','TP','SL','CADUCADA','CANCELADA')),
  exit_price numeric,
  closed_at timestamptz,
  result_r numeric,
  result_source text,
  indicators jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  closing_candle_time timestamptz,
  closing_candle_high numeric,
  closing_candle_low numeric,
  closing_candle_close numeric,
  candles_to_resolution integer
);

create table if not exists public.signal_alerts (
  id bigint generated by default as identity primary key,
  market text not null,
  timeframe text not null,
  direction text not null,
  fingerprint text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists signal_history_signal_key_uidx
  on public.signal_history (signal_key);

create unique index if not exists signal_alerts_market_timeframe_fingerprint_uidx
  on public.signal_alerts (market, timeframe, fingerprint);

create index if not exists signal_history_created_at_idx
  on public.signal_history (created_at desc);

create index if not exists signal_alerts_market_timeframe_created_at_idx
  on public.signal_alerts (market, timeframe, created_at desc);

alter table public.signal_history enable row level security;
alter table public.signal_alerts enable row level security;
